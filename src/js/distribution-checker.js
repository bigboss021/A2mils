export function initDistributionChecker() {
  const searchInput = document.getElementById('dist-search-input');
  const filterButtons = document.querySelectorAll('.dist-filter-btn');
  const districtsGrid = document.getElementById('districts-pills-grid');
  const resultCard = document.getElementById('dist-result-card');
  const countDisplay = document.getElementById('dist-count-display');

  if (!districtsGrid) return;

  let activeZone = 'all';
  let searchQuery = '';

  function renderDistricts() {
    const filtered = INDRAMAYU_DISTRICTS.filter((item) => {
      const matchZone = activeZone === 'all' || item.zone === activeZone;
      const matchSearch =
        item.name.toLowerCase().includes(searchQuery.toLowerCase()) ||
        item.zoneName.toLowerCase().includes(searchQuery.toLowerCase()) ||
        item.highlight.toLowerCase().includes(searchQuery.toLowerCase());
      return matchZone && matchSearch;
    });

    if (countDisplay) {
      countDisplay.textContent = `${filtered.length} Kecamatan Tercover`;
    }

    districtsGrid.innerHTML = '';

    if (filtered.length === 0) {
      districtsGrid.innerHTML = `
        <div class="dist-not-found">
          <p>Kecamatan "<strong>${escapeHtml(searchQuery)}</strong>" tidak ditemukan dalam daftar Kabupaten Indramayu.</p>
          <small>Silakan cek ejaan nama kecamatan atau hubungi sales untuk konfirmasi alamat pengiriman Anda.</small>
        </div>
      `;
      return;
    }

    filtered.forEach((item) => {
      const pill = document.createElement('button');
      pill.type = 'button';
      pill.className = 'district-pill-btn';
      pill.innerHTML = `
        <span class="pill-dot"></span>
        <span class="pill-name">${item.name}</span>
        <span class="pill-tag">${item.zone.toUpperCase()}</span>
      `;

      pill.addEventListener('click', () => {
        selectDistrict(item);
        document.querySelectorAll('.district-pill-btn').forEach((p) => p.classList.remove('active'));
        pill.classList.add('active');
      });

      districtsGrid.appendChild(pill);
    });
  }

  function selectDistrict(item) {
    if (!resultCard) return;

    resultCard.innerHTML = `
      <div class="dist-card-selected animate-fade-in">
        <div class="selected-header">
          <div class="selected-badge">
            <span class="pulse-dot"></span>
            <span>${item.status}</span>
          </div>
          <span class="selected-zone-tag">${item.zoneName}</span>
        </div>

        <h3 class="selected-title">Kecamatan ${item.name}</h3>
        <p class="selected-desc">${item.highlight}</p>

        <div class="selected-specs-grid">
          <div class="selected-spec-item">
            <span class="spec-label">Jadwal Armada Logistik:</span>
            <strong class="spec-val">${item.schedule}</strong>
          </div>
          <div class="selected-spec-item">
            <span class="spec-label">Estimasi Pengantaran:</span>
            <strong class="spec-val text-aqua">${item.leadTime}</strong>
          </div>
          <div class="selected-spec-item">
            <span class="spec-label">Pusat Hub Distribusi:</span>
            <strong class="spec-val">PT. Tirta Boga Mega Kreasi (Indramayu)</strong>
          </div>
          <div class="selected-spec-item">
            <span class="spec-label">Fasilitas Khusus:</span>
            <strong class="spec-val">Gratis Ongkir (Kemitraan Tertentu) & Garansi Utuh</strong>
          </div>
        </div>

        <div class="selected-actions">
          <button type="button" class="btn-primary btn-apply-district" id="btn-apply-order">
            <svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">
              <path d="M6 2L3 6v14a2 2 0 0 0 2 2h14a2 2 0 0 0 2-2V6l-3-4z"></path>
              <line x1="3" y1="6" x2="21" y2="6"></line>
              <path d="M16 10a4 4 0 0 1-8 0"></path>
            </svg>
            Pesan / Kirim ke Kec. ${item.name}
          </button>
          <a href="https://wa.me/6282115886482?text=${encodeURIComponent(
            `Halo Sales A2mils, saya ingin order/tanya kemitraan untuk pengiriman wilayah Kecamatan ${item.name}, Kabupaten Indramayu.`
          )}" target="_blank" class="btn-secondary">
            Chat WhatsApp Langsung
          </a>
        </div>
      </div>
    `;

    // Add click handler to scroll & pre-fill the order form
    const applyBtn = resultCard.querySelector('#btn-apply-order');
    if (applyBtn) {
      applyBtn.addEventListener('click', () => {
        const cityInput = document.getElementById('order-city-input');
        const formSection = document.getElementById('kemitraan');

        if (cityInput) {
          cityInput.value = `Kecamatan ${item.name}, Indramayu`;
          cityInput.focus();
        }

        if (formSection) {
          formSection.scrollIntoView({ behavior: 'smooth', block: 'start' });
        }
      });
    }
  }

  // Handle Search Input
  if (searchInput) {
    searchInput.addEventListener('input', (e) => {
      searchQuery = e.target.value.trim();
      renderDistricts();
    });
  }

  // Handle Filter Buttons
  filterButtons.forEach((btn) => {
    btn.addEventListener('click', () => {
      filterButtons.forEach((b) => b.classList.remove('active'));
      btn.classList.add('active');
      activeZone = btn.getAttribute('data-zone') || 'all';
      renderDistricts();
    });
  });

  // Initial render
  renderDistricts();

  // Pre-select first district (Indramayu Kota) for instant visual preview
  if (INDRAMAYU_DISTRICTS.length > 0) {
    selectDistrict(INDRAMAYU_DISTRICTS[0]);
  }
}

function escapeHtml(str) {
  return str.replace(/[&<>"']/g, (m) => ({
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#39;'
  }[m]));
}
